#!/usr/bin/env bash
# Writes charts/environments/cms-saas-secrets.yaml, the `secrets:` tree the
# `cms-saas` helmfile environment layers over env-secrets.yaml, from the
# releases already running on the cluster.
#
# Why: env-secrets.yaml is a template (placeholders such as pgrdemo123 and
# change-me). cms-saas's real values were only ever passed to `helm install`,
# so they live in each release's stored values and nowhere in git. The
# environment lists cms-saas-secrets.yaml explicitly, so helmfile stops with a
# missing-file error rather than deploying the placeholders over production.
#
# The output is git-ignored and written 0600. It is the union of every
# release's `secrets:` (releases were installed from slightly different env
# files, e.g. only some carry secrets.novu). A value equal to env-secrets.yaml's
# template placeholder is ignored (a release rendered from the template carries
# those). Releases are read oldest to newest by their last upgrade, and where two
# disagree the newest wins: helmfile hands every release the whole secrets: tree,
# so a partial sync (`-l name=configmaps`) leaves the others holding the value
# it replaced. The resolved keys are listed (names only).
#
# Usage: scripts/cms-saas-secrets-from-cluster.sh [kube-context]   (default ccrs-prod)
set -euo pipefail

context=${1:-ccrs-prod}
here=$(cd "$(dirname "$0")" && pwd)
out="$here/../charts/environments/cms-saas-secrets.yaml"

if [ -e "$out" ]; then
  printf '%s already exists; move it away first.\n' "$out" >&2
  exit 1
fi

umask 077
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

helm list -A --kube-context "$context" -o json > "$tmp/releases.json"
python3 - "$tmp/releases.json" > "$tmp/pairs" <<'EOF'
import json, sys
# Oldest first, so the merge below lets the most recent upgrade win.
for r in sorted(json.load(open(sys.argv[1])), key=lambda r: r["updated"]):
    print(r["namespace"], r["name"])
EOF

n=0
while read -r ns name; do
  n=$((n + 1))
  helm get values "$name" -n "$ns" --kube-context "$context" -o json > "$tmp/$(printf '%04d' "$n").$ns.$name.json"
done < "$tmp/pairs"

python3 - "$tmp" "$out" "$here/../charts/environments/env-secrets.yaml" <<'EOF'
import glob, json, os, sys
import yaml

tmp, out, template_file = sys.argv[1], sys.argv[2], sys.argv[3]
template = (yaml.safe_load(open(template_file)) or {}).get("secrets") or {}

def placeholder(path):
    node = template
    for key in path:
        if not isinstance(node, dict) or key not in node:
            return object()
        node = node[key]
    return node

resolved = set()

def merge(into, src, path):
    for key, value in src.items():
        here = path + (key,)
        if isinstance(value, dict):
            merge(into.setdefault(key, {}), value, here)
        elif value == placeholder(here):
            continue
        else:
            if key in into and into[key] != value:
                resolved.add("secrets." + ".".join(here))
            into[key] = value

secrets = {}
# The files are numbered oldest to newest; later ones override earlier ones.
for f in sorted(glob.glob(os.path.join(tmp, "[0-9]*.json"))):
    values = json.load(open(f)) or {}
    merge(secrets, values.get("secrets") or {}, ())

if not secrets:
    sys.exit("no release carries a secrets: tree; nothing written")

with open(out, "w") as fh:
    fh.write("# Generated by scripts/cms-saas-secrets-from-cluster.sh. Git-ignored; do not commit.\n")
    yaml.safe_dump({"secrets": secrets}, fh, sort_keys=True)
print(f"wrote {out}: secrets.{{{', '.join(sorted(secrets))}}}")
for key in sorted(resolved):
    print(f"  releases disagreed on {key}: kept the most recently upgraded release's value")
EOF
