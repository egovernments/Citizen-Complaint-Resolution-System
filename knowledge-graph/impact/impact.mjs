#!/usr/bin/env node
// Impact query: "if X changes, what is affected?"
//   node knowledge-graph/impact/impact.mjs <node-id[,node-id…] | search text> [options]
// Options:
//   --depth N            max hops to follow (default 4)
//   --rels a,b           only follow these relationship types
//   --confirmed          ignore inferred edges
//   --mermaid FILE       also write the impact subgraph as a Mermaid flowchart
//   --title TEXT         heading for the Mermaid file
//   --mermaid-depth N    only draw nodes up to N hops in the Mermaid file (default: --depth)
//   --deps               reverse the question: what does X depend on?
//   --list               list matching node ids and exit
// Edges point from the dependent to its dependency, so impact walks edges backwards.
import { writeFileSync } from "node:fs";
import { dependenciesIndex, dependentsIndex, loadGraph, prefixOf } from "./lib.mjs";

const args = process.argv.slice(2);
const opt = (name, dflt) => { const i = args.indexOf(name); return i === -1 ? dflt : args[i + 1]; };
const flag = (name) => args.includes(name);
const VALUE_OPTS = ["--depth", "--rels", "--mermaid", "--title", "--mermaid-depth"];
const query = args.find((a, i) => !a.startsWith("--") && !VALUE_OPTS.includes(args[i - 1]));
if (!query) {
  console.error("usage: impact.mjs <node-id[,node-id…] | search text> [--depth N] [--rels a,b] [--confirmed] [--deps] [--mermaid FILE] [--title TEXT] [--list]");
  process.exit(2);
}

const { nodes, edges } = loadGraph();
const maxDepth = Number(opt("--depth", 4));
const rels = opt("--rels") ? new Set(opt("--rels").split(",")) : null;
const usable = edges.filter((e) => (!rels || rels.has(e.rel)) && (!flag("--confirmed") || e.status === "confirmed"));

const q = query.toLowerCase();
const exact = query.split(",").map((s) => s.trim()).filter((s) => nodes.has(s));
const starts = exact.length ? exact : [...nodes.keys()].filter((id) => id.toLowerCase().includes(q) || (nodes.get(id).label || "").toLowerCase().includes(q));
if (flag("--list") || starts.length === 0) {
  console.log(starts.length ? starts.join("\n") : `No node matches "${query}".`);
  process.exit(starts.length ? 0 : 1);
}
if (starts.length > 12 && !exact.length) {
  console.error(`"${query}" matches ${starts.length} nodes; use an exact id (see --list).`);
  process.exit(2);
}

const deps = flag("--deps");
const index = deps ? dependenciesIndex(usable) : dependentsIndex(usable);
const next = (e) => (deps ? e.to : e.from);

// Breadth-first walk, remembering the first edge that reached each node.
const reached = new Map(starts.map((s) => [s, { depth: 0, via: null }]));
const subEdges = [];
let frontier = [...starts];
for (let d = 1; d <= maxDepth && frontier.length; d++) {
  const nextFrontier = [];
  for (const id of frontier) {
    for (const e of index.get(id) || []) {
      subEdges.push(e);
      const n = next(e);
      if (!reached.has(n)) { reached.set(n, { depth: d, via: e }); nextFrontier.push(n); }
    }
  }
  frontier = nextFrontier;
}

const GROUPS = [
  ["screen", "Screens"], ["api", "First-party APIs"], ["class", "Java classes"], ["code", "Code / config modules"],
  ["topic", "Kafka topics"], ["table", "Tables / views"], ["field", "Fields"], ["master", "MDMS masters"],
  ["wf", "Workflow states / actions"], ["service", "Deployables"], ["infra", "Deploy / CI artefacts"],
  ["test", "Tests"], ["config", "Config keys"], ["coreapi", "DIGIT core APIs"], ["ext", "External systems"], ["biz", "Business concepts"],
];
console.log(`${deps ? "Dependencies of" : "Impact of changing"}: ${starts.join(", ")}  (depth ≤ ${maxDepth}${rels ? `, rels ${[...rels]}` : ""}${flag("--confirmed") ? ", confirmed only" : ""})\n`);
for (const [p, title] of GROUPS) {
  const hits = [...reached].filter(([id, r]) => r.depth > 0 && prefixOf(id) === p).sort((a, b) => a[1].depth - b[1].depth || a[0].localeCompare(b[0]));
  if (!hits.length) continue;
  console.log(`${title} (${hits.length})`);
  for (const [id, r] of hits) {
    const e = r.via;
    const mark = e.status === "confirmed" ? "" : ` [${e.status}]`;
    const where = e.evidence ? `${e.evidence.file}:${e.evidence.line}` : `(${e.note})`;
    console.log(`  ${"·".repeat(r.depth)} ${id}  ←${e.rel}— ${deps ? e.from : e.to}${mark}   ${where}`);
  }
  console.log("");
}
console.log(`Total affected: ${reached.size - starts.length} nodes via ${new Set(subEdges).size} edges.`);

const out = opt("--mermaid");
if (out) {
  const safe = (id) => "n" + Buffer.from(id).toString("hex").slice(0, 40) + id.length;
  const esc = (s) => String(s).replace(/"/g, "'").replace(/[<>]/g, "");
  const drawDepth = Number(opt("--mermaid-depth", maxDepth));
  const drawn = new Set([...reached].filter(([, r]) => r.depth <= drawDepth).map(([id]) => id));
  const ids = [...drawn];
  const lines = [
    `%% Generated by knowledge-graph/impact/impact.mjs — do not edit by hand.`,
    `%% Query: ${query}${deps ? " (--deps)" : ""}, drawn to depth ${drawDepth} of ${maxDepth}${rels ? `, rels ${[...rels]}` : ""}. Solid = confirmed, dotted = inferred or derived (context path → deployable).`,
    `%% Arrows point from the affected element to what it depends on.`,
    "flowchart RL",
  ];
  if (opt("--title")) lines.splice(1, 0, `%% ${opt("--title")}`);
  // One column per hop: Changed → 1 hop → 2 hops …, each node tagged with its type.
  const TAG = {
    screen: "screen", api: "API", class: "Java class", code: "code / config", topic: "Kafka topic", table: "table / view",
    field: "field", master: "MDMS master", wf: "workflow", service: "deployable", infra: "deploy / CI", test: "test",
    config: "config key", coreapi: "DIGIT core API", ext: "external", biz: "business",
  };
  const COLOR = {
    screen: "screen", api: "app", class: "app", code: "app", config: "app", test: "test",
    table: "data", field: "data", master: "data", topic: "int", coreapi: "int", ext: "int",
    service: "infra", infra: "infra", wf: "biz", biz: "biz",
  };
  for (let d = 0; d <= drawDepth; d++) {
    const list = ids.filter((id) => reached.get(id).depth === d)
      .sort((a, b) => GROUPS.findIndex(([p]) => p === prefixOf(a)) - GROUPS.findIndex(([p]) => p === prefixOf(b)) || a.localeCompare(b));
    if (!list.length) continue;
    const title = d === 0 ? "Changed" : `${d} hop${d > 1 ? "s" : ""} away (${list.length})`;
    lines.push(`  subgraph D${d}["${title}"]`, "    direction TB");
    for (const id of list) {
      const n = nodes.get(id);
      lines.push(`    ${safe(id)}["<small>${TAG[prefixOf(id)]}</small><br/>${esc(n.label || id)}"]:::${d === 0 ? "changed" : COLOR[prefixOf(id)]}`);
    }
    lines.push("  end");
  }
  const seen = new Set();
  const drawnEdges = [];
  for (const e of subEdges) {
    if (!drawn.has(e.from) || !drawn.has(e.to)) continue;
    // Draw the ripple only: each edge must lead one step closer to the changed node(s).
    const [near, far] = deps ? [e.from, e.to] : [e.to, e.from];
    if (reached.get(near).depth >= reached.get(far).depth) continue;
    const key = `${e.from}|${e.to}`;
    if (seen.has(key)) continue;
    seen.add(key);
    drawnEdges.push(e);
  }
  const labelled = drawnEdges.length <= 60; // edge labels only where they stay legible; the .txt report has every rel
  for (const e of drawnEdges) {
    const arrow = e.status === "confirmed" ? "-->" : "-.->";
    lines.push(`  ${safe(e.from)} ${arrow}${labelled ? `|"${e.rel}"|` : ""} ${safe(e.to)}`);
  }
  lines.push(
    "  classDef changed fill:#ffe9e4,stroke:#d4002a,stroke-width:3px,color:#4a1408",
    "  classDef screen fill:#fff4dd,stroke:#a8741a,color:#3d2a06",
    "  classDef app fill:#e3edff,stroke:#2d5fb8,color:#0f2350",
    "  classDef test fill:#f5f5f5,stroke:#9aa0a6,color:#3c4043",
    "  classDef data fill:#e4f5ec,stroke:#1f7a4d,color:#0b3320",
    "  classDef int fill:#f1e8ff,stroke:#6a3fa3,color:#2b1450",
    "  classDef infra fill:#eceff2,stroke:#56606b,color:#1d242b",
    "  classDef biz fill:#fdecc8,stroke:#a8741a,color:#3d2a06",
  );
  writeFileSync(out, lines.join("\n") + "\n");
  console.log(`Mermaid written to ${out}`);
}
