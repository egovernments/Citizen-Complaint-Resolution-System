#!/usr/bin/env node
// Writes knowledge-graph/layers/0-overview.mmd: the five layers with node counts and the
// cross-layer links between them (edge counts by relationship), computed from graph/*.json.
//   node knowledge-graph/impact/layers.mjs
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { HERE, LAYERS, loadGraph, prefixOf } from "./lib.mjs";

const { nodes, edges } = loadGraph();
const TITLE = { business: "1 · Business", application: "2 · Application", data: "3 · Data", integration: "4 · Integration", infrastructure: "5 · Infrastructure" };
const FILE = { business: "1-business.mmd", application: "2-application.mmd", data: "3-data.mmd", integration: "4-integration.mmd", infrastructure: "5-infrastructure.mmd" };

const byLayer = Object.fromEntries(LAYERS.map((l) => [l, {}]));
for (const n of nodes.values()) {
  const p = prefixOf(n.id);
  byLayer[n.layer][p] = (byLayer[n.layer][p] || 0) + 1;
}

const links = new Map(); // "a|b" -> {rel: count}
for (const e of edges) {
  const a = nodes.get(e.from).layer, b = nodes.get(e.to).layer;
  if (a === b) continue;
  const k = `${a}|${b}`;
  if (!links.has(k)) links.set(k, {});
  links.get(k)[e.rel] = (links.get(k)[e.rel] || 0) + 1;
}

const lines = [
  "%% Generated by knowledge-graph/impact/layers.mjs from impact/graph/*.json — do not edit by hand.",
  "%% The five layers of the CCRS knowledge graph. Box = layer with its node counts by type.",
  "%% Arrow = cross-layer dependencies (dependent → dependency), labelled with total edges and the top relationships.",
  "%% Each layer has its own diagram in this folder; impact/impact.mjs walks all layers at once.",
  "flowchart TB",
];
for (const l of LAYERS) {
  const parts = Object.entries(byLayer[l]).sort((a, b) => b[1] - a[1]).map(([p, c]) => `${c} ${p}`).join(" · ");
  const total = Object.values(byLayer[l]).reduce((s, c) => s + c, 0);
  lines.push(`  ${l}["<b>${TITLE[l]}</b> (${total} nodes)<br/><small>${parts}</small><br/><small>${FILE[l]}</small>"]:::${l}`);
}
for (const [k, rels] of [...links].sort((a, b) => sum(b[1]) - sum(a[1]))) {
  const [a, b] = k.split("|");
  const top = Object.entries(rels).sort((x, y) => y[1] - x[1]).slice(0, 3).map(([r, c]) => `${r} ${c}`).join(", ");
  lines.push(`  ${a} -->|"${sum(rels)}: ${top}"| ${b}`);
}
lines.push(
  "  classDef business fill:#fff4dd,stroke:#a8741a,color:#3d2a06",
  "  classDef application fill:#e3edff,stroke:#2d5fb8,color:#0f2350",
  "  classDef data fill:#e4f5ec,stroke:#1f7a4d,color:#0b3320",
  "  classDef integration fill:#f1e8ff,stroke:#6a3fa3,color:#2b1450",
  "  classDef infrastructure fill:#eceff2,stroke:#56606b,color:#1d242b",
);
function sum(o) { return Object.values(o).reduce((s, c) => s + c, 0); }

const out = join(HERE, "..", "layers", "0-overview.mmd");
writeFileSync(out, lines.join("\n") + "\n");
console.log(`Wrote ${out}`);
