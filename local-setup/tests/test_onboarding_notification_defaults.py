#!/usr/bin/env python3
"""The notification defaults pgr-services gives a new workspace are the deploy's own, not a copy that
drifts: backend/pgr-services/src/main/resources/onboarding/notification-defaults.json is generated by
local-setup/scripts/build-onboarding-notification-defaults.py from seed-notifications.py and the
default-data-handler files, and this test fails as soon as it is stale.

Run: python3 -m unittest local-setup/tests/test_onboarding_notification_defaults.py
"""
import importlib.util
import json
import os
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SCRIPTS = os.path.join(REPO, "local-setup", "scripts")


def _load(name, filename):
    spec = importlib.util.spec_from_file_location(name, os.path.join(SCRIPTS, filename))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


build = _load("build_onboarding_notification_defaults", "build-onboarding-notification-defaults.py")
sn = _load("seed_notifications_for_packaging_test", "seed-notifications.py")

try:
    import jinja2
except ImportError:  # pragma: no cover
    # CI installs it (local-setup-ci.yaml, config-contracts): there it must fail, not skip.
    if os.environ.get("CI"):
        raise
    jinja2 = None


class PackagedDefaults(unittest.TestCase):

    def test_the_packaged_file_is_what_the_generator_makes_now(self):
        with open(build.OUT, encoding="utf-8") as fh:
            committed = fh.read()
        self.assertEqual(build.render(build.build()), committed,
                         "stale: run local-setup/scripts/build-onboarding-notification-defaults.py")

    def test_it_carries_the_seeders_access_rows_and_the_shipped_configuration(self):
        doc = build.build()
        by = {}
        for r in doc["records"]:
            by.setdefault(r["schemaCode"], []).append(r["data"])
        self.assertEqual(sorted(a["id"] for a in by[sn.ACTION_SCHEMA]), sorted(a[0] for a in sn.NOTIF_ACTIONS))
        granted = {(ra["rolecode"], ra["actionid"]) for ra in by[sn.ROLEACTION_SCHEMA]}
        wanted = {(role, a[0]) for a in sn.NOTIF_ACTIONS for role in a[6]}
        self.assertEqual(granted, wanted, "every role the seeder grants exists in a workspace")
        ddh = os.path.join(build.DDH, "mdmsData-dev", "NOTIFICATIONS")
        for code in ("NOTIFICATIONS.Template", "NOTIFICATIONS.ProviderTemplate", "NOTIFICATIONS.Routing",
                     "NOTIFICATIONS.EventCatalogue"):
            with open(os.path.join(ddh, code + ".json"), encoding="utf-8") as fh:
                self.assertEqual(by[code], json.load(fh), code)
        self.assertNotIn("NOTIFICATIONS.Channel", by, "channel rows follow the deployment allowlist instead")
        self.assertEqual([s["code"] for s in doc["schemas"]], sn.NOTIF_CODES + sn.NEW_CODES)
        self.assertEqual([r["schemaCode"] for r in doc["records"]][-1], "NOTIFICATIONS.Routing", "routing last")

    def test_check_mode_fails_on_a_stale_file(self):
        original = build.OUT
        stale = os.path.join(HERE, ".stale-notification-defaults.json")
        with open(stale, "w", encoding="utf-8") as fh:
            fh.write("{}\n")
        self.addCleanup(os.remove, stale)
        self.addCleanup(setattr, build, "OUT", original)
        build.OUT = stale
        import contextlib
        import io
        with contextlib.redirect_stderr(io.StringIO()):
            self.assertEqual(build.main(["--check"]), 1)


@unittest.skipIf(jinja2 is None, "needs jinja2 (ansible's own dependency)")
class TheStepFollowsEnableNovu(unittest.TestCase):
    """Review of #2342: PGR_ONBOARDING_NOTIFICATION_DEFAULTS_ENABLED was set nowhere, so a deployment
    without the notification stack wrote ~180 unused rows into every new workspace."""

    @classmethod
    def setUpClass(cls):
        with open(os.path.join(REPO, "local-setup", "ansible", "templates", "digit.env.j2"), encoding="utf-8") as fh:
            lines = [l for l in fh.read().splitlines() if l.startswith("PGR_ONBOARDING_NOTIFICATION_DEFAULTS_ENABLED=")]
        cls.lines = lines
        env = jinja2.Environment()
        # Ansible's `bool` filter, as far as these values go.
        env.filters["bool"] = lambda v: v if isinstance(v, bool) else str(v).strip().lower() in ("1", "true", "yes", "on")
        cls.template = env.from_string(lines[0]) if lines else None

    def render(self, **values):
        return self.template.render(**values).split("=", 1)[1]

    def test_the_env_file_renders_it_once_from_enable_novu(self):
        self.assertEqual(len(self.lines), 1)
        self.assertEqual(self.render(enable_novu=True), "true")
        self.assertEqual(self.render(enable_novu=False), "false")
        self.assertEqual(self.render(), "false", "enable_novu unset: the notification stack is off")
        self.assertEqual(self.render(enable_novu=True, pgr_onboarding_notification_defaults_enabled=False), "false")
        self.assertEqual(self.render(enable_novu=False, pgr_onboarding_notification_defaults_enabled="true"), "true")

    def test_compose_passes_it_to_pgr_services_off_by_default(self):
        with open(os.path.join(REPO, "local-setup", "docker-compose.egov-digit.yaml"), encoding="utf-8") as fh:
            compose = fh.read()
        self.assertEqual(compose.count("PGR_ONBOARDING_NOTIFICATION_DEFAULTS_ENABLED: "
                                       "${PGR_ONBOARDING_NOTIFICATION_DEFAULTS_ENABLED:-false}"), 1)

    def test_helm_sets_it_with_the_runner(self):
        with open(os.path.join(REPO, "devops", "deploy-as-code", "charts", "urban", "pgr-services", "values.yaml"),
                  encoding="utf-8") as fh:
            values = fh.read()
        self.assertIn("  notificationDefaultsEnabled: true\n", values)
        self.assertIn("- name: PGR_ONBOARDING_NOTIFICATION_DEFAULTS_ENABLED\n"
                      "    value: {{ .Values.onboarding.notificationDefaultsEnabled | quote }}", values)


if __name__ == "__main__":
    unittest.main()
